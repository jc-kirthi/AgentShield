"""AgentShield shared contracts and models."""

from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


class Decision(str, Enum):
    ALLOW = "ALLOW"
    HOLD = "HOLD"
    DENY = "DENY"


class ReasonCode(str, Enum):
    # Success
    ALLOW_OK = "ALLOW_OK"

    # Holds
    HOLD_BANK_NAME_PARTIAL = "HOLD_BANK_NAME_PARTIAL"
    HOLD_BANK_COOLING_OFF = "HOLD_BANK_COOLING_OFF"
    HOLD_BANK_CHANGE_UNDER_REVIEW = "HOLD_BANK_CHANGE_UNDER_REVIEW"
    HOLD_ORACLE_UNAVAILABLE = "HOLD_ORACLE_UNAVAILABLE"
    HOLD_AMOUNT_NEEDS_APPROVAL = "HOLD_AMOUNT_NEEDS_APPROVAL"

    # Denials
    DENY_AGENT_UNAUTHENTICATED = "DENY_AGENT_UNAUTHENTICATED"
    DENY_LEASE_INVALID = "DENY_LEASE_INVALID"
    DENY_LEASE_EXPIRED = "DENY_LEASE_EXPIRED"
    DENY_LEASE_REVOKED = "DENY_LEASE_REVOKED"
    DENY_LEASE_SUSPENDED = "DENY_LEASE_SUSPENDED"
    DENY_CALL_BUDGET_EXHAUSTED = "DENY_CALL_BUDGET_EXHAUSTED"
    DENY_NONCE_REUSED = "DENY_NONCE_REUSED"
    DENY_STALE_REQUEST = "DENY_STALE_REQUEST"
    DENY_SCHEMA_INVALID = "DENY_SCHEMA_INVALID"
    DENY_TOOL_NOT_IN_SCOPE = "DENY_TOOL_NOT_IN_SCOPE"
    DENY_OBJECT_NOT_IN_SCOPE = "DENY_OBJECT_NOT_IN_SCOPE"
    DENY_AMOUNT_EXCEEDS_LEASE = "DENY_AMOUNT_EXCEEDS_LEASE"
    DENY_PRICE_VARIANCE = "DENY_PRICE_VARIANCE"
    DENY_QTY_EXCEEDS_GR = "DENY_QTY_EXCEEDS_GR"
    DENY_BANK_NAME_MISMATCH = "DENY_BANK_NAME_MISMATCH"
    DENY_DUPLICATE_PAYMENT = "DENY_DUPLICATE_PAYMENT"
    DENY_INVOICE_NOT_PAYABLE = "DENY_INVOICE_NOT_PAYABLE"
    DENY_AMOUNT_MISMATCH = "DENY_AMOUNT_MISMATCH"
    DENY_FREIGHT_UNECONOMIC = "DENY_FREIGHT_UNECONOMIC"
    DENY_SIGNAL_CONTRADICTED = "DENY_SIGNAL_CONTRADICTED"
    DENY_CONCURRENT_MODIFICATION = "DENY_CONCURRENT_MODIFICATION"
    DENY_DENIAL_BUDGET_EXHAUSTED = "DENY_DENIAL_BUDGET_EXHAUSTED"
    DENY_POLICY_ERROR = "DENY_POLICY_ERROR"
    DENY_DEPENDENCY_UNAVAILABLE = "DENY_DEPENDENCY_UNAVAILABLE"


class EventEnvelope(BaseModel):
    model_config = ConfigDict(extra="forbid")
    event_id: str
    topic: str
    source: Literal["gateway", "agent", "erp_sim", "attacklab", "oracles"]
    timestamp: str
    correlation_id: str
    actor: str
    payload: Dict[str, Any] = Field(default_factory=dict)
    prev_hash: str = "0" * 64
    entry_hash: Optional[str] = None
